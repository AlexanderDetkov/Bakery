"""Knowledge propagation in an EQUIVALENCE-RELATION world: the sibling of `bake_theorem_qa` whose
truth is SYMMETRIC "same kind" (the reflexive/symmetric/transitive closure = same weakly-connected
component) instead of DIRECTED reachability.

Same gated `theorem_qa` builder, same KL primitive, same held-out-by-proof-depth d′ readout — only
`data.relation_mode="equivalence"` flips the proof-system instrument: the `ProofEngine` symmetrizes
each edge, `relations.candidate_pools` yields same-component TRUE pairs (BOTH orders) with
cross-component pairs as the ONLY negative family (no converse / missing-edge), and the question
becomes "are X and Y the same kind?". This isolates whether baking propagates a SYMMETRIC relation
(where the converse of every taught edge is also true) differently from the directed is-a relation.

The eq_* assets (worlds / prompt / QA probe bank) are a disjoint-vocab namespace generated by
`scripts/make_logic_world.py --relation-mode equivalence`. Headline model is Llama-3.1-8B-Instruct.
Curriculum depth is `--data.train_max_depth`; bake vs SFT is `--train.objective`.
"""

import bakery.trajectories.theorem_qa as theorem_qa  # noqa: F401 — registers the builder
from bakery.registry import register_experiment

register_experiment(
    "bake_theorem_qa_equiv",
    builder_name="theorem_qa",
    data_config_cls=theorem_qa.TheoremQADataConfig,
    objective="bake",
    extra_metrics=("eval_kl", "dprime"),
    defaults={
        "model": {"name": "meta-llama/Llama-3.1-8B-Instruct", "lora_rank": 16, "lora_alpha": 16},
        "generation": {
            "base_prompt": "data/prompts/eq_alpha_u.md",
            "baked_prompt": "data/prompts/empty.md",
            "max_new_tokens": 32,
            "trajectories_per_context": 4,
            "do_sample": True,
        },
        "train": {"num_epochs": 100, "batch_size": 8, "learning_rate": 3e-4,
                  "lr_schedule": "constant", "cache_teacher_logits": "cpu",
                  "eval_period": 2, "save_every": 20, "save_adapters": True},
        "eval": {"metrics": ["eval_kl", "dprime"]},
        "regularization": {"num_train_contexts": 0, "eval_num_contexts": 16,
                           "source": "squad", "context_split": "validation",
                           "max_new_tokens": 40, "do_sample": False, "seed": 0},
        "data": {
            "relation_mode": "equivalence",
            "world_spec": "data/worlds/eq_alpha.json",
            "probe_bank": "data/probes/eq_alpha_qa_probes.json",
            "train_max_depth": 1,
            "per_depth_train_cap": 16,
            "split_seed": 0,
        },
    },
    description="Same-kind (SYMMETRIC, rst-closure) analogue of bake_theorem_qa: a logic world whose "
                "truth is 'X and Y in the same weakly-connected component'. relation_mode=equivalence "
                "flips the engine/pools/phrasing; held-out propagation by undirected depth via d′.",
)
